#!/usr/bin/env python3
"""Differential check of split compilations on random multi-module programs.

For each seed, writes a program of several modules, each a progfuzz.py program
(whose main becomes a function the program's main calls) importing a module of
templates they all instantiate, so that template instances are shared across
modules. Each program is then checked by ../splitcheck.py: compiled with -j=1 and
with -j=2, 3 and 8, to an object file and to a library, with and without
-O -inline -release, the outputs compared symbol by symbol, and the -j=N outputs
compiled several times compared byte for byte. The program built from the -j=3
object file must also print what the one built from the -j=1 object file prints.

Usage:
  splitfuzz.py SEEDS [--modules K] [--dmd DMD] [--work DIR] [-j N] [--size SIZE]

SEEDS is a number, a range FROM-TO, or a comma separated list of them. A failing
seed's program and the checker's report are kept in WORK/fail/split-SEED/. The
exit status is 1 when any seed failed.
"""

import argparse
import concurrent.futures
import os
import re
import shutil
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import progfuzz                         # noqa: E402
from fuzz import DEFAULT_DMD, parse_seeds, run   # noqa: E402

CHECKER = os.path.join(HERE, '..', 'splitcheck.py')

SHARED = '''// generated by splitfuzz.py: the templates every module instantiates
module fzshared;
T tmin(T)(T a, T b) { return a < b ? a : b; }
T tmax(T)(T a, T b) { return a < b ? b : a; }
T tmix(T)(T a, T b) { return cast(T)((a ^ (b << 5)) + (b >>> 2)); }
'''

TEMPLATES = re.compile(r'^T t(min|max|mix)\(T\).*\n', re.M)


def write_program(seed, modules, size, directory):
    """Writes the modules of the program of `seed` to `directory`; returns their files"""
    os.makedirs(directory, exist_ok=True)
    files = []
    with open(os.path.join(directory, 'fzshared.d'), 'w') as f:
        f.write(SHARED)
    files.append('fzshared.d')
    calls = []
    for i in range(modules):
        name = 'fzm%d' % i
        text = progfuzz.Gen(seed * 100 + i, size).program()
        text = re.sub(r'^module fz\d+;', 'module %s;\nimport fzshared;' % name, text, count=1, flags=re.M)
        text = TEMPLATES.sub('', text)
        text = text.replace('void main()', 'void run%d()' % i, 1)
        with open(os.path.join(directory, name + '.d'), 'w') as f:
            f.write(text)
        files.append(name + '.d')
        calls.append('    %s.run%d();' % (name, i))
    with open(os.path.join(directory, 'main.d'), 'w') as f:
        f.write('import %s;\nvoid main()\n{\n%s\n}\n' % (', '.join('fzm%d' % i for i in range(modules)),
                                                        '\n'.join(calls)))
    return files


def check(seed, args):
    """Returns None if the program of `seed` passes, else a report"""
    directory = os.path.join(args.work, 'split-%d' % seed)
    shutil.rmtree(directory, ignore_errors=True)
    files = write_program(seed, args.modules, args.size, directory)
    env = {'DMD_NEWCG': '1'}
    report = []
    for flags in (['-O', '-inline', '-release'], []):
        for output in (['-c', '-of=all.o'], ['-lib', '-of=all.a']):
            status, out = run([sys.executable, CHECKER, '-j', '2,3,8', '-r', '2', '--require-split', '--cwd',
                               directory, '--', args.dmd] + flags + output + files, env=env, timeout=1800)
            if status != 0:
                report.append('splitcheck %s %s:\n%s' % (' '.join(flags), ' '.join(output), out))
        # the program runs the same with the code of either
        outputs = []
        for j in ('1', '3'):
            obj = 'modules%s.o' % j
            status, out = run([args.dmd, '-j=' + j, '-c', '-of=' + obj] + flags + files, env=env, cwd=directory)
            if status == 0:
                exe = os.path.join(directory, 'p' + j)
                status, out = run([args.dmd, '-of=' + exe, 'main.d', obj] + flags, env=env, cwd=directory)
            if status == 0:
                status, out = run([exe], cwd=directory, timeout=60)
            outputs.append((status, out))
        if outputs[0] != outputs[1]:
            report.append('with %s, -j=1 runs (%s):\n%s\n-j=3 runs (%s):\n%s' % (
                ' '.join(flags), outputs[0][0], outputs[0][1], outputs[1][0], outputs[1][1]))
    if not report:
        shutil.rmtree(directory, ignore_errors=True)
        return None
    fail = os.path.join(args.work, 'fail', 'split-%d' % seed)
    shutil.rmtree(fail, ignore_errors=True)
    shutil.copytree(directory, fail)
    shutil.rmtree(directory, ignore_errors=True)
    text = '\n'.join(report)
    with open(os.path.join(fail, 'report.txt'), 'w') as f:
        f.write(text)
    return text


def main():
    ap = argparse.ArgumentParser(description=__doc__.split('\n\n')[0])
    ap.add_argument('seeds')
    ap.add_argument('--modules', type=int, default=6)
    ap.add_argument('--size', choices=['small', 'medium', 'large'], default='medium')
    ap.add_argument('--dmd', default=os.environ.get('FUZZ_DMD', DEFAULT_DMD))
    ap.add_argument('--work', default=os.environ.get('FUZZ_WORK', os.path.join(
        os.environ.get('TMPDIR', '/tmp'), 'dmd-fuzz')))
    ap.add_argument('-j', '--jobs', type=int, default=1)
    args = ap.parse_args()
    os.makedirs(os.path.join(args.work, 'fail'), exist_ok=True)
    failed = 0
    seeds = parse_seeds(args.seeds)
    with concurrent.futures.ThreadPoolExecutor(args.jobs) as ex:
        for seed, report in zip(seeds, ex.map(lambda s: check(s, args), seeds)):
            if report:
                failed += 1
                print('split %d: FAIL, see %s' % (seed, os.path.join(args.work, 'fail', 'split-%d' % seed)))
                print('    ' + report.splitlines()[0])
    print('split: %d of %d seeds failed' % (failed, len(seeds)))
    return 1 if failed else 0


if __name__ == '__main__':
    sys.exit(main())
